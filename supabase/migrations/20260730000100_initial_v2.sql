CREATE OR REPLACE FUNCTION public.create_appointment(
  p_provider_id UUID,
  p_service_id BIGINT,
  p_starts_at TIMESTAMPTZ,
  p_message TEXT DEFAULT NULL
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE v_id UUID;
BEGIN
  IF auth.uid() IS NULL OR p_starts_at <= NOW() THEN
    RAISE EXCEPTION 'invalid appointment';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(p_provider_id::TEXT, 0));
  IF NOT EXISTS (
    SELECT 1 FROM public.provider_services
    WHERE provider_id = p_provider_id AND service_id = p_service_id
  ) THEN RAISE EXCEPTION 'provider does not offer service'; END IF;
  IF EXISTS (
    SELECT 1 FROM public.provider_blocks
    WHERE provider_id = p_provider_id
      AND starts_at < p_starts_at + INTERVAL '1 hour'
      AND ends_at > p_starts_at
  ) THEN RAISE EXCEPTION 'slot is unavailable'; END IF;
  IF EXISTS (
    SELECT 1 FROM public.bookings
    WHERE provider_id = p_provider_id
      AND status IN ('pending', 'confirmed')
      AND starts_at < p_starts_at + INTERVAL '1 hour'
      AND COALESCE(ends_at, starts_at + INTERVAL '1 hour') > p_starts_at
  ) THEN RAISE EXCEPTION 'slot is unavailable'; END IF;
  INSERT INTO public.bookings(client_id, provider_id, service_id, kind, starts_at, message)
  VALUES (auth.uid(), p_provider_id, p_service_id, 'appointment', p_starts_at, NULLIF(BTRIM(p_message), ''))
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_stay_booking(
  p_venue_id UUID,
  p_starts_at TIMESTAMPTZ,
  p_ends_at TIMESTAMPTZ,
  p_guest_count INTEGER,
  p_message TEXT DEFAULT NULL
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE v_id UUID;
BEGIN
  IF auth.uid() IS NULL OR p_starts_at < CURRENT_DATE OR p_ends_at <= p_starts_at OR p_guest_count <= 0 THEN
    RAISE EXCEPTION 'invalid stay booking';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(p_venue_id::TEXT, 0));
  IF NOT EXISTS (
    SELECT 1 FROM public.venue_profiles
    WHERE id = p_venue_id AND (capacity = 0 OR capacity >= p_guest_count)
  ) THEN
    RAISE EXCEPTION 'venue not found';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.provider_blocks
    WHERE provider_id = p_venue_id
      AND starts_at < p_ends_at AND ends_at > p_starts_at
  ) THEN RAISE EXCEPTION 'dates are unavailable'; END IF;
  IF EXISTS (
    SELECT 1 FROM public.bookings
    WHERE provider_id = p_venue_id
      AND status IN ('pending', 'confirmed')
      AND starts_at < p_ends_at
      AND COALESCE(ends_at, starts_at + INTERVAL '1 hour') > p_starts_at
  ) THEN RAISE EXCEPTION 'dates are unavailable'; END IF;
  INSERT INTO public.bookings(client_id, provider_id, kind, starts_at, ends_at, guest_count, message)
  VALUES (auth.uid(), p_venue_id, 'stay', p_starts_at, p_ends_at, p_guest_count, NULLIF(BTRIM(p_message), ''))
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.transition_booking(p_booking_id UUID, p_status public.booking_status)
RETURNS public.bookings
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE v_booking public.bookings;
BEGIN
  SELECT * INTO v_booking FROM public.bookings WHERE id = p_booking_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'booking not found'; END IF;
  IF public.is_admin() THEN
    INSERT INTO public.audit_logs(actor_id, action, target_type, target_id, metadata)
    VALUES (auth.uid(), 'booking_override', 'booking', p_booking_id::TEXT, jsonb_build_object('from', v_booking.status, 'to', p_status));
  ELSIF auth.uid() = v_booking.client_id THEN
    IF p_status <> 'cancelled' OR v_booking.status NOT IN ('pending', 'confirmed') THEN
      RAISE EXCEPTION 'transition not allowed';
    END IF;
  ELSIF auth.uid() = v_booking.provider_id THEN
    IF NOT (
      (v_booking.status = 'pending' AND p_status IN ('confirmed', 'rejected'))
      OR (v_booking.status = 'confirmed' AND p_status = 'completed' AND v_booking.starts_at <= NOW())
    ) THEN RAISE EXCEPTION 'transition not allowed'; END IF;
  ELSE
    RAISE EXCEPTION 'not allowed';
  END IF;
  UPDATE public.bookings SET status = p_status WHERE id = p_booking_id RETURNING * INTO v_booking;
  RETURN v_booking;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_provider_unavailable_intervals(
  p_provider_id UUID,
  p_from TIMESTAMPTZ,
  p_to TIMESTAMPTZ
)
RETURNS TABLE(starts_at TIMESTAMPTZ, ends_at TIMESTAMPTZ)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT block.starts_at, block.ends_at
  FROM public.provider_blocks block
  WHERE auth.uid() IS NOT NULL
    AND block.provider_id = p_provider_id
    AND p_to > p_from
    AND p_to <= p_from + INTERVAL '370 days'
    AND block.starts_at < p_to AND block.ends_at > p_from
  UNION ALL
  SELECT booking.starts_at, COALESCE(booking.ends_at, booking.starts_at + INTERVAL '1 hour')
  FROM public.bookings booking
  WHERE auth.uid() IS NOT NULL
    AND booking.provider_id = p_provider_id
    AND booking.status IN ('pending', 'confirmed')
    AND p_to > p_from
    AND p_to <= p_from + INTERVAL '370 days'
    AND booking.starts_at < p_to
    AND COALESCE(booking.ends_at, booking.starts_at + INTERVAL '1 hour') > p_from;
$$;

CREATE OR REPLACE FUNCTION public.admin_set_user_banned(p_user_id UUID, p_banned BOOLEAN)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NOT public.is_admin() OR p_user_id = auth.uid() THEN RAISE EXCEPTION 'not allowed'; END IF;
  UPDATE public.profiles SET is_banned = p_banned WHERE id = p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'user not found'; END IF;
  INSERT INTO public.audit_logs(actor_id, action, target_type, target_id, metadata)
  VALUES (auth.uid(), 'set_user_banned', 'profile', p_user_id::TEXT, jsonb_build_object('is_banned', p_banned));
END;
$$;

CREATE OR REPLACE FUNCTION public.set_initial_role(p_role public.account_role, p_city TEXT DEFAULT NULL)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'not_authenticated'; END IF;
  UPDATE public.profiles
  SET role = p_role, city = COALESCE(NULLIF(BTRIM(p_city), ''), city)
  WHERE id = auth.uid() AND role IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'role_already_selected'; END IF;

  IF p_role = 'specialist' THEN
    INSERT INTO public.specialist_profiles(id) VALUES (auth.uid()) ON CONFLICT DO NOTHING;
  ELSIF p_role = 'venue' THEN
    INSERT INTO public.venue_profiles(id) VALUES (auth.uid()) ON CONFLICT DO NOTHING;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_or_create_direct_conversation(p_partner_id UUID)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE v_id UUID;
BEGIN
  IF auth.uid() IS NULL OR p_partner_id = auth.uid() THEN RAISE EXCEPTION 'invalid partner'; END IF;
  PERFORM pg_advisory_xact_lock(
    hashtextextended(LEAST(auth.uid()::TEXT, p_partner_id::TEXT) || GREATEST(auth.uid()::TEXT, p_partner_id::TEXT), 0)
  );
  IF EXISTS (
    SELECT 1 FROM public.blocks
    WHERE (blocker_id = auth.uid() AND blocked_id = p_partner_id)
       OR (blocker_id = p_partner_id AND blocked_id = auth.uid())
  ) THEN RAISE EXCEPTION 'conversation is blocked'; END IF;
  SELECT c.id INTO v_id
  FROM public.conversations c
  JOIN public.conversation_members mine ON mine.conversation_id = c.id AND mine.user_id = auth.uid()
  JOIN public.conversation_members partner ON partner.conversation_id = c.id AND partner.user_id = p_partner_id
  WHERE c.kind = 'direct'
    AND (SELECT COUNT(*) FROM public.conversation_members cm WHERE cm.conversation_id = c.id) = 2
  LIMIT 1;
  IF v_id IS NULL THEN
    INSERT INTO public.conversations(kind) VALUES ('direct') RETURNING id INTO v_id;
    INSERT INTO public.conversation_members(conversation_id, user_id)
    VALUES (v_id, auth.uid()), (v_id, p_partner_id);
  END IF;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_my_chats()
RETURNS TABLE (
  conversation_id UUID,
  partner_id UUID,
  full_name TEXT,
  avatar_url TEXT,
  last_message TEXT,
  last_message_time TIMESTAMPTZ
)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT
    c.id,
    partner.user_id,
    p.full_name,
    p.avatar_url,
    last_message.content,
    last_message.created_at
  FROM public.conversations c
  JOIN public.conversation_members mine ON mine.conversation_id = c.id AND mine.user_id = auth.uid()
  JOIN public.conversation_members partner ON partner.conversation_id = c.id AND partner.user_id <> auth.uid()
  JOIN public.profiles p ON p.id = partner.user_id
  LEFT JOIN LATERAL (
    SELECT m.content, m.created_at FROM public.messages m
    WHERE m.conversation_id = c.id AND NOT m.is_hidden
    ORDER BY m.created_at DESC LIMIT 1
  ) last_message ON TRUE
  WHERE c.kind = 'direct'
  ORDER BY last_message.created_at DESC NULLS LAST;
$$;

CREATE OR REPLACE FUNCTION public.mark_conversation_read(p_conversation_id UUID)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.conversations c
    WHERE c.id = p_conversation_id
      AND (
        c.kind = 'category'
        OR EXISTS (
          SELECT 1 FROM public.conversation_members cm
          WHERE cm.conversation_id = c.id AND cm.user_id = auth.uid()
        )
      )
  ) THEN RAISE EXCEPTION 'conversation_not_accessible'; END IF;

  INSERT INTO public.conversation_members(conversation_id, user_id, last_read_at)
  VALUES (p_conversation_id, auth.uid(), NOW())
  ON CONFLICT (conversation_id, user_id)
  DO UPDATE SET last_read_at = EXCLUDED.last_read_at;
END;
$$;

CREATE OR REPLACE FUNCTION public.register_device_token(p_token TEXT, p_platform TEXT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = private, public, pg_temp
AS $$
BEGIN
  IF auth.uid() IS NULL OR p_platform NOT IN ('android', 'ios') OR BTRIM(p_token) = '' THEN
    RAISE EXCEPTION 'invalid token';
  END IF;
  INSERT INTO private.device_tokens(user_id, token, platform)
  VALUES (auth.uid(), p_token, p_platform)
  ON CONFLICT (token) DO UPDATE SET user_id = EXCLUDED.user_id, platform = EXCLUDED.platform, updated_at = NOW();
END;
$$;

CREATE OR REPLACE FUNCTION public.unregister_device_token(p_token TEXT)
RETURNS VOID
LANGUAGE SQL
SECURITY DEFINER
SET search_path = private, public, pg_temp
AS $$
  DELETE FROM private.device_tokens
