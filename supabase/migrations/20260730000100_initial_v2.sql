CREATE OR REPLACE VIEW public.provider_search_view
WITH (security_invoker = true)
AS
SELECT
  p.id,
  p.full_name,
  p.avatar_url,
  p.city,
  p.role::TEXT AS provider_type,
  c.slug AS category_slug,
  c.name AS category_name,
  s.slug AS service_slug,
  s.id AS service_id,
  s.name AS service_name,
  COALESCE(ps.price_from, sp.price_start, vp.price_from, 0) AS price_from,
  sp.experience_years,
  sp.service_area,
  vp.capacity,
  vp.location_zone,
  NULL::DOUBLE PRECISION AS latitude,
  NULL::DOUBLE PRECISION AS longitude,
  vp.distance_to_beach_m,
  COALESCE(AVG(r.rating) FILTER (WHERE NOT r.is_hidden), 0)::NUMERIC(3,2) AS avg_rating,
  COUNT(r.id) FILTER (WHERE NOT r.is_hidden) AS review_count
FROM public.profiles p
JOIN public.provider_services ps ON ps.provider_id = p.id
JOIN public.services s ON s.id = ps.service_id AND s.is_active
JOIN public.service_categories c ON c.id = s.category_id AND c.is_active
LEFT JOIN public.specialist_profiles sp ON sp.id = p.id
LEFT JOIN public.venue_profiles vp ON vp.id = p.id
LEFT JOIN public.reviews r ON r.target_id = p.id
WHERE NOT p.is_banned
  AND NOT EXISTS (
    SELECT 1 FROM public.blocks b
    WHERE auth.uid() IS NOT NULL
      AND (
        (b.blocker_id = auth.uid() AND b.blocked_id = p.id)
        OR (b.blocker_id = p.id AND b.blocked_id = auth.uid())
      )
  )
GROUP BY p.id, c.slug, c.name, s.id, s.slug, s.name, ps.price_from, sp.price_start, sp.experience_years,
  sp.service_area, vp.price_from, vp.capacity, vp.location_zone, vp.distance_to_beach_m;

CREATE OR REPLACE FUNCTION public.search_providers(
  p_provider_type public.provider_type DEFAULT NULL,
  p_category_slug TEXT DEFAULT NULL,
  p_service_slug TEXT DEFAULT NULL,
  p_city TEXT DEFAULT NULL,
  p_max_price NUMERIC DEFAULT NULL,
  p_sort TEXT DEFAULT 'rating',
  p_latitude DOUBLE PRECISION DEFAULT NULL,
  p_longitude DOUBLE PRECISION DEFAULT NULL
)
RETURNS TABLE(
  id UUID,
  full_name TEXT,
  avatar_url TEXT,
  city TEXT,
  provider_type TEXT,
  category_slug TEXT,
  category_name TEXT,
  service_slug TEXT,
  service_id BIGINT,
  service_name TEXT,
  price_from NUMERIC,
  experience_years INTEGER,
  service_area TEXT,
  capacity INTEGER,
  location_zone TEXT,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  distance_to_beach_m INTEGER,
  avg_rating NUMERIC,
  review_count BIGINT,
  distance_km DOUBLE PRECISION
)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = private, public, pg_temp
AS $$
  SELECT
    v.id, v.full_name, v.avatar_url, v.city, v.provider_type,
    v.category_slug, v.category_name, v.service_slug, v.service_id,
    v.service_name, v.price_from, v.experience_years, v.service_area, v.capacity, v.location_zone,
    location.latitude,
    location.longitude,
    v.distance_to_beach_m, v.avg_rating, v.review_count,
    CASE
      WHEN v.provider_type = 'venue'
        AND p_latitude IS NOT NULL AND p_longitude IS NOT NULL
        AND location.latitude IS NOT NULL AND location.longitude IS NOT NULL
      THEN 6371 * acos(LEAST(1, GREATEST(-1,
        cos(radians(p_latitude)) * cos(radians(location.latitude))
        * cos(radians(location.longitude) - radians(p_longitude))
        + sin(radians(p_latitude)) * sin(radians(location.latitude))
      )))
    END AS distance_km
  FROM public.provider_search_view v
  LEFT JOIN private.venue_locations location
    ON location.provider_id = v.id AND location.is_public AND v.provider_type = 'venue'
  WHERE (p_provider_type IS NULL OR v.provider_type = p_provider_type::TEXT)
    AND (p_category_slug IS NULL OR v.category_slug = p_category_slug)
    AND (p_service_slug IS NULL OR v.service_slug = p_service_slug)
    AND (p_city IS NULL OR v.city ILIKE '%' || p_city || '%')
    AND (p_max_price IS NULL OR v.price_from <= p_max_price)
  ORDER BY
    CASE WHEN p_sort = 'price' THEN v.price_from END ASC NULLS LAST,
    CASE WHEN p_sort = 'distance' THEN
      CASE
        WHEN v.provider_type = 'venue'
          AND p_latitude IS NOT NULL AND p_longitude IS NOT NULL
          AND location.latitude IS NOT NULL AND location.longitude IS NOT NULL
        THEN 6371 * acos(LEAST(1, GREATEST(-1,
          cos(radians(p_latitude)) * cos(radians(location.latitude))
          * cos(radians(location.longitude) - radians(p_longitude))
          + sin(radians(p_latitude)) * sin(radians(location.latitude))
        )))
      END
    END ASC NULLS LAST,
    v.avg_rating DESC,
    v.full_name ASC;
$$;

