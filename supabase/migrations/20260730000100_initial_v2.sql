CREATE OR REPLACE FUNCTION public.moderate_report(
  p_report_id UUID,
  p_action TEXT,
  p_note TEXT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE v_report public.reports%ROWTYPE;
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'admin_required'; END IF;
  IF p_action NOT IN ('hide', 'dismiss') THEN RAISE EXCEPTION 'invalid_action'; END IF;

  SELECT * INTO v_report FROM public.reports WHERE id = p_report_id FOR UPDATE;
  IF NOT FOUND OR v_report.status <> 'open' THEN RAISE EXCEPTION 'report_not_open'; END IF;

  IF p_action = 'hide' THEN
    CASE v_report.target_type
      WHEN 'profile' THEN UPDATE public.profiles SET is_banned = TRUE WHERE id = v_report.target_id;
      WHEN 'message' THEN UPDATE public.messages SET is_hidden = TRUE WHERE id = v_report.target_id;
      WHEN 'review' THEN UPDATE public.reviews SET is_hidden = TRUE WHERE id = v_report.target_id;
      WHEN 'portfolio' THEN UPDATE public.portfolio_items SET is_hidden = TRUE WHERE id = v_report.target_id;
      ELSE RAISE EXCEPTION 'invalid_target_type';
    END CASE;
  END IF;

  UPDATE public.reports
  SET status = CASE WHEN p_action = 'hide' THEN 'resolved' ELSE 'dismissed' END,
      resolution_note = NULLIF(trim(p_note), ''),
      updated_at = NOW()
  WHERE id = p_report_id;

  INSERT INTO public.audit_logs(actor_id, action, target_type, target_id, metadata)
  VALUES (
    auth.uid(), 'moderate_report_' || p_action, v_report.target_type, v_report.target_id::TEXT,
    jsonb_build_object('report_id', p_report_id, 'note', p_note)
  );
END;
$$;

