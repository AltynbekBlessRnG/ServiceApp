BEGIN
  IF auth.uid() IS NULL THEN RETURN FALSE; END IF;
  INSERT INTO private.ai_usage(user_id, window_started_at, request_count)
  VALUES (auth.uid(), v_window, 1)
  ON CONFLICT (user_id, window_started_at)
